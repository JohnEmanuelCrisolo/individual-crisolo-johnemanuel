
package com.joysistvi.day6.ifstatement;

public class ifElseStatement {
    public static void main(String[] args) {

        int age = 18;
        String result;

        if (age >= 18) {
            result = "Valid Age";
        } else {
            result = "Invalid Age";
        }

        System.out.println(result);
    }
}
