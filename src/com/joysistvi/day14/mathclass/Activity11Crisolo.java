package com.joysistvi.day14.mathclass;
public class Activity11Crisolo {
    public static void main(String[] args) {

        // 1. Math.abs()
        // Removes the negative sign.
        System.out.println("Absolute: " + Math.abs(-10));


        // 2. Math.max()
        // Gets the bigger number.
        System.out.println("Maximum: " + Math.max(20, 67));


        // 3. Math.min()
        // Gets the smaller number.
        System.out.println("Minimum: " + Math.min(10, 20));


        // 4. Math.pow()
        // Raises a number to a power.
        // 2 x 2 x 2 = 8
        System.out.println("Power: " + Math.pow(2, 3));


        // 5. Math.sqrt()
        // Gets the square root.
        System.out.println("Square Root: " + Math.sqrt(25));


        // 6. Math.round()
        // Rounds to the nearest whole number.
        System.out.println("Round: " + Math.round(4.6));


        // 7. Math.ceil()
        // Always rounds up.
        System.out.println("Ceiling: " + Math.ceil(4.1));


        // 8. Math.floor()
        // Always rounds down.
        System.out.println("Floor: " + Math.floor(4.8));


        // 9. Math.random()
        // Generates a random decimal between 0.0 and 1.0.
        System.out.printf("Random: %.2f", Math.random());


        // 10. Math.log()
        // Gets the natural logarithm (base e).
        System.out.println("\nNatural Log: " + Math.log(5));


        // 11. Math.log10()
        // Gets the logarithm with base 10.
        System.out.println("Log Base 10: " + Math.log10(100));


        // 12. Math.exp()
        // Calculates e raised to a power.
        System.out.println("Exponential: " + Math.exp(1));


        // 13. Math.sin()
        // Calculates the sine of an angle in radians.
        System.out.println("Sine: " + Math.sin(2));


        // 14. Math.cos()
        // Calculates the cosine of an angle in radians.
        System.out.println("Cosine: " + Math.cos(30));


        // 15. Math.tan()
        // Calculates the tangent of an angle in radians.
        System.out.println("Tangent: " + Math.tan(10));
    }
}

